"""Transparent signal model.

Every factor is computed here from Upstox candles (and the Upstox option chain when available) and returned
with its raw inputs, the rule that scored it, its weight and its contribution, so the UI can show exactly how a
recommendation was produced. Weights, the trade gate and the confidence table come from
data/signal_calibration.json, which is generated by replaying the engine against Stock Mantra Index calls and
measuring real outcomes. Nothing here invents a price: missing data makes a factor "unavailable" (weight 0).
"""
from __future__ import annotations

import json
import math
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

IST = timezone(timedelta(hours=5, minutes=30))
CALIBRATION_PATH = Path(__file__).resolve().parents[2] / "data" / "signal_calibration.json"

DEFAULT_CALIBRATION: dict[str, Any] = {
    "version": "uncalibrated",
    "weights": {"trend": 0.25, "vwap": 0.20, "momentum": 0.20, "price_action": 0.20, "day_change": 0.15, "option_flow": 0.0},
    "gate": 40.0,
    "min_agree": 3,
    "buckets": [],
    "source": "Default weights; no calibration file found",
}

FACTOR_INFO = {
    "trend": ("Trend", "EMA 9 / 21 / 50 on 5m candles", "±40 for EMA9 vs EMA21, ±30 for EMA21 vs EMA50, plus (EMA9−EMA21)/ATR×30"),
    "vwap": ("VWAP position", "Session VWAP and ATR(14) on 5m", "(Price − VWAP) ÷ ATR ÷ 1.5 × 100"),
    "momentum": ("Momentum", "RSI(14) and MACD(12,26,9) histogram on 5m", "(RSI − 50) × 3, ±25 when the MACD histogram expands"),
    "price_action": ("Price action", "15-minute opening range and last 2-hour swing", "±60 outside the opening range, ±40 beyond the swing high/low"),
    "day_change": ("Day change", "Session open and ATR(14) on 5m", "(Price − day open) ÷ ATR ÷ 3 × 100"),
    "option_flow": ("Option flow", "Upstox option chain ATM ±3 strikes", "PE OI change vs CE OI change, scaled to ±100"),
}


def load_calibration() -> dict[str, Any]:
    try:
        data = json.loads(CALIBRATION_PATH.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("weights"):
            return data
    except Exception:
        pass
    return dict(DEFAULT_CALIBRATION)


def _ts(c: dict[str, Any]) -> datetime | None:
    try:
        return datetime.fromisoformat(str(c.get("timestamp")).replace("Z", "+00:00")).astimezone(IST)
    except Exception:
        return None


def _ema(vals: list[float], n: int) -> list[float]:
    k = 2 / (n + 1)
    e = vals[0]
    out = []
    for v in vals:
        e = v * k + e * (1 - k)
        out.append(e)
    return out


def _clamp(x: float) -> float:
    return max(-100.0, min(100.0, x))


def compute_factors(candles_5m: list[dict[str, Any]], option_chain: dict[str, Any] | None = None) -> dict[str, Any]:
    """Factor scores (−100 bearish … +100 bullish) with the raw inputs behind each one."""
    cs = [c for c in candles_5m if c.get("close") is not None]
    if len(cs) < 60:
        return {"available": False, "reason": f"Need at least 60 five-minute candles from Upstox, got {len(cs)}"}
    closes = [float(c["close"]) for c in cs]
    px = closes[-1]
    last_t = _ts(cs[-1])
    e9, e21, e50 = _ema(closes, 9)[-1], _ema(closes, 21)[-1], _ema(closes, 50)[-1]
    gains = [max(0.0, closes[i] - closes[i - 1]) for i in range(len(closes) - 14, len(closes))]
    losses = [max(0.0, closes[i - 1] - closes[i]) for i in range(len(closes) - 14, len(closes))]
    rsi = 100 - 100 / (1 + (sum(gains) / 14) / max(1e-9, sum(losses) / 14))
    macd = [a - b for a, b in zip(_ema(closes, 12), _ema(closes, 26))]
    sig = _ema(macd, 9)
    hist, hist_prev = macd[-1] - sig[-1], macd[-2] - sig[-2]
    trs = [max(float(cs[i]["high"]) - float(cs[i]["low"]), abs(float(cs[i]["high"]) - closes[i - 1]), abs(float(cs[i]["low"]) - closes[i - 1]))
           for i in range(len(cs) - 14, len(cs))]
    atr = max(sum(trs) / len(trs), 1e-6)

    day = [c for c in cs if _ts(c) and last_t and _ts(c).date() == last_t.date()]
    if not day:
        day = cs[-1:]
    vol = sum(float(c.get("volume") or 0) for c in day)
    tp = [(float(c["high"]) + float(c["low"]) + float(c["close"])) / 3 for c in day]
    vwap = sum(t * float(c.get("volume") or 0) for t, c in zip(tp, day)) / vol if vol > 0 else sum(tp) / len(tp)
    vwap_basis = "volume-weighted" if vol > 0 else "equal-weight (index has no volume)"
    orb = day[:3]  # first three 5m candles = 15-minute opening range
    orb_hi, orb_lo = max(float(c["high"]) for c in orb), min(float(c["low"]) for c in orb)
    day_open = float(day[0]["open"])
    swing = closes[-25:-1]
    swing_hi, swing_lo = max(swing), min(swing)

    scores = {
        "trend": _clamp(((e9 > e21) - (e9 < e21)) * 40 + ((e21 > e50) - (e21 < e50)) * 30 + _clamp((e9 - e21) / atr * 30)),
        "vwap": _clamp((px - vwap) / atr / 1.5 * 100),
        "momentum": _clamp((rsi - 50) * 3 + (25 if hist > 0 and hist > hist_prev else -25 if hist < 0 and hist < hist_prev else 0)),
        "price_action": _clamp((60 if px > orb_hi else -60 if px < orb_lo else 0) + (40 if px > swing_hi else -40 if px < swing_lo else 0)),
        "day_change": _clamp((px - day_open) / atr / 3 * 100),
    }
    inputs = {
        "trend": f"EMA9 {e9:,.1f} · EMA21 {e21:,.1f} · EMA50 {e50:,.1f}",
        "vwap": f"Price {px:,.1f} vs VWAP {vwap:,.1f} ({vwap_basis}), ATR {atr:,.1f}",
        "momentum": f"RSI {rsi:.1f} · MACD hist {hist:+.2f} (prev {hist_prev:+.2f})",
        "price_action": f"OR {orb_lo:,.1f}–{orb_hi:,.1f} · swing {swing_lo:,.1f}–{swing_hi:,.1f}",
        "day_change": f"Open {day_open:,.1f} → {px:,.1f} ({px - day_open:+,.1f})",
    }
    flow = _option_flow(option_chain, px)
    if flow is not None:
        scores["option_flow"] = flow["score"]
        inputs["option_flow"] = flow["text"]
    return {
        "available": True,
        "scores": {k: round(v, 1) for k, v in scores.items()},
        "inputs": inputs,
        "raw": {"price": px, "ema9": e9, "ema21": e21, "ema50": e50, "rsi": rsi, "macd_hist": hist, "atr": atr, "vwap": vwap,
                "orb_high": orb_hi, "orb_low": orb_lo, "swing_high": swing_hi, "swing_low": swing_lo, "day_open": day_open},
        "as_of": last_t.isoformat() if last_t else None,
    }


def _option_flow(chain: dict[str, Any] | None, spot: float) -> dict[str, Any] | None:
    """Put-side vs call-side OI change near the money. Rising put OI (writers) is read as support → bullish."""
    try:
        strikes = (chain or {}).get("strikes") or []
        if not strikes:
            return None
        near = sorted(strikes, key=lambda s: abs(float(s.get("strike") or 0) - spot))[:7]
        ce = sum(float(((s.get("call") or {}).get("oi_change") or (s.get("call") or {}).get("change_oi") or 0)) for s in near)
        pe = sum(float(((s.get("put") or {}).get("oi_change") or (s.get("put") or {}).get("change_oi") or 0)) for s in near)
        tot = abs(ce) + abs(pe)
        if tot <= 0:
            return None
        score = _clamp((pe - ce) / tot * 100)
        return {"score": score, "text": f"ATM±3 OI change · PE {pe:+,.0f} vs CE {ce:+,.0f}"}
    except Exception:
        return None


def evaluate(candles_5m: list[dict[str, Any]], option_chain: dict[str, Any] | None = None, source_label: str = "Upstox") -> dict[str, Any]:
    """Weighted score, trade decision and a row-by-row explanation."""
    cal = load_calibration()
    f = compute_factors(candles_5m, option_chain)
    if not f.get("available"):
        return {"available": False, "reason": f.get("reason"), "calibration": _cal_summary(cal)}
    weights = {k: float(v) for k, v in cal["weights"].items()}
    used = {k: w for k, w in weights.items() if k in f["scores"] and w > 0}
    wsum = sum(used.values()) or 1.0
    rows, total = [], 0.0
    for key, w in weights.items():
        name, src, rule = FACTOR_INFO.get(key, (key, "", ""))
        if key not in f["scores"]:
            rows.append({"key": key, "name": name, "available": False, "input": "Not available from Upstox right now", "source": src,
                         "rule": rule, "points": None, "weight_pct": 0.0, "contribution": 0.0})
            continue
        eff_w = (w / wsum) if key in used else 0.0
        contrib = f["scores"][key] * eff_w
        total += contrib
        rows.append({"key": key, "name": name, "available": True, "input": f["inputs"][key], "source": f"{source_label} · {src}",
                     "rule": rule, "points": f["scores"][key], "weight_pct": round(eff_w * 100, 1), "contribution": round(contrib, 1)})
    total = round(total, 1)
    gate = float(cal.get("gate", 40))
    direction_rows = [r for r in rows if r["available"] and r["weight_pct"] > 0]
    agree_bull = sum(1 for r in direction_rows if r["points"] > 0)
    agree_bear = sum(1 for r in direction_rows if r["points"] < 0)
    need = int(cal.get("min_agree", 3))
    if total >= gate and agree_bull >= need:
        decision = "BUY"
    elif total <= -gate and agree_bear >= need:
        decision = "SELL"
    else:
        decision = "NO_TRADE"
    conf = confidence_for(abs(total), cal)
    return {
        "available": True,
        "decision": decision,
        "score": total,
        "gate": gate,
        "agreeing": agree_bull if total >= 0 else agree_bear,
        "factors_used": len(direction_rows),
        "min_agree": need,
        "rows": rows,
        "raw": f["raw"],
        "as_of": f["as_of"],
        "confidence": conf,
        "calibration": _cal_summary(cal),
    }


def confidence_for(abs_score: float, cal: dict[str, Any] | None = None) -> dict[str, Any]:
    """Measured hit-rate of past signals with a similar score. Returns None values when not measured yet."""
    cal = cal or load_calibration()
    for b in cal.get("buckets") or []:
        if float(b["lo"]) <= abs_score < float(b["hi"]) and int(b.get("n") or 0) > 0:
            n, hit = int(b["n"]), int(b["hit"])
            return {"pct": round(hit / n * 100, 1), "n": n, "hit": hit, "label": f"{hit}/{n} past signals in this score range moved 0.3% in the signal direction first"}
    return {"pct": None, "n": 0, "hit": 0, "label": "Not measured yet for this score range"}


def _cal_summary(cal: dict[str, Any]) -> dict[str, Any]:
    return {k: cal.get(k) for k in ("version", "source", "generated", "gate", "min_agree", "weights", "validation")}
